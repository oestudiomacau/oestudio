const languageSelect = document.querySelector("#language-select");
const description = document.querySelector('meta[name="description"]');
const translatable = [
  ["copy", "textContent"],
  ["alt", "alt"],
  ["label", "aria-label"],
].flatMap(([key, target]) =>
  Array.from(document.querySelectorAll("[data-" + key + "]"), (element) => ({
    element,
    target,
    path: element.dataset[key].split("."),
  }))
);

function applyLanguage(language) {
  const copy = translations[language];
  document.documentElement.lang = language;
  document.title = copy.title;
  description.content = copy.description;
  languageSelect.value = language;

  for (const { element, target, path } of translatable) {
    const value = path.reduce((entry, part) => entry[part], copy);
    if (target === "textContent") {
      element.textContent = value;
    } else {
      element.setAttribute(target, value);
    }
  }
}

const languageKey = "oe-studio-language";
let initialLanguage = document.documentElement.lang;
try {
  const savedLanguage = localStorage.getItem(languageKey);
  if (Object.hasOwn(translations, savedLanguage)) initialLanguage = savedLanguage;
} catch {
  // The language selector also works when storage is unavailable.
}
applyLanguage(initialLanguage);
languageSelect.hidden = false;

languageSelect.addEventListener("change", () => {
  applyLanguage(languageSelect.value);
  try {
    localStorage.setItem(languageKey, languageSelect.value);
  } catch {
    // Keep the selected language for the current visit.
  }
});

for (const gallery of document.querySelectorAll("[data-gallery]")) {
  const slides = Array.from(gallery.querySelectorAll(".project-images img"));
  const controls = gallery.querySelector(".gallery-controls");
  const count = gallery.querySelector(".gallery-count");
  let active = 0;

  function move(step) {
    const next = (active + step + slides.length) % slides.length;
    const slide = slides[next];
    if (!slide.hasAttribute("src")) slide.src = slide.dataset.src;
    slides[active].hidden = true;
    slide.hidden = false;
    active = next;
    count.textContent = (active + 1) + " / " + slides.length;
  }

  for (const button of controls.querySelectorAll("[data-step]")) {
    button.addEventListener("click", () => move(Number(button.dataset.step)));
  }
  controls.hidden = false;
}
